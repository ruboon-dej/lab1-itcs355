"""Pipeline definitions (Layer 3: provider SDKs are allowed here).

pipeline/pipeline.yaml is the neutral spec; this module turns it into an Azure ML pipeline.
Step logic stays in the images: every step is `cd /app && python ...` on one of two images
(train image for ingest/validate/train, ops image for gate/register).

The gate is enforced in code: the gate step writes decision.json and the register step reads it,
registering only when passed is true. A rejected candidate leaves the registry unchanged and the
register step logs "NOT REGISTERED". (An Azure ML if_else node was tried first; it needs mlflow and
azureml-mlflow inside the step image to report the control output, which the hash-locked images
do not carry. See compile_condition_test, kept as evidence of that attempt.)
"""
import os
import subprocess
import time
from pathlib import Path
from typing import Any, Optional

ROOT = Path(__file__).resolve().parents[1]
SPEC_PATH = ROOT / "pipeline" / "pipeline.yaml"


def load_spec(path: Path = SPEC_PATH) -> dict[str, Any]:
    import yaml

    return yaml.safe_load(Path(path).read_text())


def _file(name: str, default: str = "") -> str:
    p = ROOT / name
    return p.read_text().strip() if p.exists() else default


def images() -> dict[str, str]:
    return {
        "train": os.environ.get("TRAIN_IMAGE") or _file(".image_uri", "<run: make image-push>"),
        "ops": os.environ.get("OPS_IMAGE") or _file(".image_ops_uri", "<run: make image-ops-push>"),
    }


def _git_sha() -> str:
    try:
        return subprocess.check_output(["git", "rev-parse", "HEAD"], cwd=ROOT, text=True).strip()
    except Exception:
        return "unknown"


def step_env(params: dict[str, Any], imgs: dict[str, str]) -> dict[str, str]:
    env = {k: os.environ[k] for k in
           ("AZURE_SUBSCRIPTION_ID", "AZURE_RESOURCE_GROUP", "AZURE_ML_WORKSPACE",
            "MODEL_REGISTRY_NAME") if os.environ.get(k)}
    if os.environ.get("TRAIN_UAI_CLIENT_ID"):
        env["UAI_CLIENT_ID"] = os.environ["TRAIN_UAI_CLIENT_ID"]
    env["GIT_COMMIT"] = _git_sha()
    env["IMAGE_DIGEST"] = imgs["train"].split("@")[-1]
    env["DVC_DATA_VERSION"] = f"generated by make_dataset.py --seed {params['data_seed']}"
    return env


def compile_azure(spec: Optional[dict] = None, overrides: Optional[dict] = None,
                  imgs: Optional[dict] = None, compute_name: Optional[str] = None):
    """Build (do not submit) the Azure ML pipeline job."""
    from azure.ai.ml import Input, Output, command, dsl
    from azure.ai.ml.entities import Environment

    from src import config

    spec = spec or load_spec()
    params = {**spec["parameters"], **(overrides or {})}
    params["allow_bootstrap"] = str(params["allow_bootstrap"]).lower()
    imgs = imgs or images()
    compute_name = compute_name or os.environ.get("TRAIN_COMPUTE", "itcs355-lab5-cpu")
    timeout = int(spec["compute"]["step_timeout_seconds"])
    env_vars = step_env(params, imgs)
    train_env = Environment(image=imgs["train"])
    ops_env = Environment(image=imgs["ops"])

    ingest_c = command(
        name="ingest", display_name="ingest",
        command="cd /app && python scripts/make_dataset.py --seed ${{inputs.data_seed}} "
                "--out ${{outputs.data}}/sensors.csv",
        inputs={"data_seed": Input(type="integer")},
        outputs={"data": Output(type="uri_folder")},
        environment=train_env, environment_variables=env_vars)

    validate_c = command(
        name="validate", display_name="validate (data contracts)",
        command="cd /app && mkdir -p data/raw && cp ${{inputs.data}}/sensors.csv data/raw/sensors.csv "
                "&& python -m pytest -q -p no:cacheprovider tests/test_data.py "
                "&& echo contract-tests-passed > ${{outputs.report}}/contract.txt",
        inputs={"data": Input(type="uri_folder")},
        outputs={"report": Output(type="uri_folder")},
        environment=train_env, environment_variables=env_vars)

    train_c = command(
        name="train", display_name="train",
        command="cd /app && test -f ${{inputs.contract}}/contract.txt "
                "&& env -u MLFLOW_RUN_ID -u MLFLOW_EXPERIMENT_ID -u MLFLOW_EXPERIMENT_NAME "
                "MLFLOW_TRACKING_URI=sqlite:////tmp/mlflow.db python -m src.train "
                "--data-path ${{inputs.data}}/sensors.csv --n-estimators ${{inputs.n_estimators}} "
                "--max-depth ${{inputs.max_depth}} --min-samples-leaf ${{inputs.min_samples_leaf}} "
                "--seed ${{inputs.model_seed}} --metrics-out ${{outputs.model_dir}}/metrics.json",
        inputs={"data": Input(type="uri_folder"), "contract": Input(type="uri_folder"),
                "n_estimators": Input(type="integer"), "max_depth": Input(type="integer"),
                "min_samples_leaf": Input(type="integer"), "model_seed": Input(type="integer")},
        outputs={"model_dir": Output(type="uri_folder")},
        environment=train_env, environment_variables=env_vars)

    gate_c = command(
        name="gate", display_name="evaluation gate",
        command="cd /app && python scripts/evaluation_gate.py --pipeline-mode --provider azure "
                "--model-name $MODEL_REGISTRY_NAME --compare-stage production "
                "--metrics ${{inputs.model_dir}}/metrics.json --metric val_roc_auc "
                "--floor ${{inputs.floor}} --margin ${{inputs.margin}} "
                "--allow-bootstrap ${{inputs.allow_bootstrap}} "
                "--decision-out ${{outputs.decision}}/decision.json",
        inputs={"model_dir": Input(type="uri_folder"), "floor": Input(type="number"),
                "margin": Input(type="number"), "allow_bootstrap": Input(type="string")},
        outputs={"decision": Output(type="uri_folder")},
        environment=ops_env, environment_variables=env_vars)

    register_c = command(
        name="register", display_name="register (only if gate passed)",
        command="cd /app && python scripts/register_model.py --provider azure "
                "--model-name $MODEL_REGISTRY_NAME --model-dir ${{inputs.model_dir}} "
                "--decision ${{inputs.decision}}/decision.json --stage staging",
        inputs={"model_dir": Input(type="uri_folder"), "decision": Input(type="uri_folder")},
        environment=ops_env, environment_variables=env_vars)

    @dsl.pipeline(name=spec["name"], display_name=spec["name"],
                  description="ingest, validate, train, gate, register-if-passed")
    def retrain(data_seed: int, model_seed: int, n_estimators: int, max_depth: int,
                min_samples_leaf: int, floor: float, margin: float, allow_bootstrap: str):
        ing = ingest_c(data_seed=data_seed)
        val = validate_c(data=ing.outputs.data)
        trn = train_c(data=ing.outputs.data, contract=val.outputs.report,
                      n_estimators=n_estimators, max_depth=max_depth,
                      min_samples_leaf=min_samples_leaf, model_seed=model_seed)
        gate = gate_c(model_dir=trn.outputs.model_dir, floor=floor, margin=margin,
                      allow_bootstrap=allow_bootstrap)
        reg = register_c(model_dir=trn.outputs.model_dir, decision=gate.outputs.decision)
        for node in (ing, val, trn, gate, reg):
            node.set_limits(timeout=timeout)

    job = retrain(**{k: params[k] for k in (
        "data_seed", "model_seed", "n_estimators", "max_depth", "min_samples_leaf",
        "floor", "margin", "allow_bootstrap")})
    job.settings.default_compute = compute_name
    job.tags = config.load(strict=False).tags(5)
    return job


def compile_condition_test(flag: str, imgs: Optional[dict] = None, compute_name: Optional[str] = None):
    """Tiny three-node pipeline that only proves dsl.condition routes. ~2 minutes of compute."""
    from azure.ai.ml import Input, Output, command, dsl
    from azure.ai.ml.dsl._condition import condition
    from azure.ai.ml.entities import CommandComponent, Environment

    from src import config

    imgs = imgs or images()
    compute_name = compute_name or os.environ.get("TRAIN_COMPUTE", "itcs355-lab5-cpu")
    env = Environment(image=imgs["train"])

    write = ('if [ -d "${{outputs.go}}" ]; then printf %s "${{inputs.flag}}" > "${{outputs.go}}/output"; '
             'else printf %s "${{inputs.flag}}" > "${{outputs.go}}"; fi; echo wrote ${{inputs.flag}}')
    decide_c = CommandComponent(name="decide", command=write, inputs={"flag": Input(type="string")},
                                outputs={"go": Output(type="boolean", is_control=True)}, environment=env)
    yes_c = command(name="yes_branch", command="echo YES-BRANCH-RAN", environment=env)
    no_c = command(name="no_branch", command="echo NO-BRANCH-RAN", environment=env)

    @dsl.pipeline(name="itcs355-lab5-condition-test")
    def probe(flag: str):
        d = decide_c(flag=flag)
        y = yes_c()
        n = no_c()
        for node in (d, y, n):
            node.set_limits(timeout=600)
        condition(d.outputs.go, true_block=y, false_block=n)

    job = probe(flag=flag)
    job.settings.default_compute = compute_name
    job.tags = config.load(strict=False).tags(5)
    return job


def compile_for(provider: str, **kwargs):
    """`make pipeline`: compile the spec for this provider and show what would run."""
    if provider != "azure":
        raise NotImplementedError(f"pipeline compilation is only implemented for azure, not {provider!r}")
    job = compile_azure(**kwargs)
    print(f"compiled {job.name or job.display_name}: steps = {', '.join(job.jobs)}")
    return job


def submit(job, experiment: str, skip_validation: bool = False):
    from cloudlayer import azure_ops

    # azure-ai-ml 1.35: the local schema check rejects an if_else node inside a PipelineJob and then
    # crashes formatting the error (KeyError: 0). Only the condition test needs the bypass.
    return azure_ops.ml_client().jobs.create_or_update(
        job, experiment_name=experiment, skip_validation=skip_validation)


def _norm(status) -> str:
    """SDK statuses arrive as 'JobStatus.FAILED' or an enum; return 'Failed', 'Completed', ..."""
    return str(getattr(status, "value", status)).split(".")[-1].strip().capitalize()


def wait(name: str, timeout_s: int = 1800, poll_s: int = 20) -> str:
    from cloudlayer import azure_ops

    client = azure_ops.ml_client()
    deadline = time.time() + timeout_s
    status = ""
    while time.time() < deadline:
        status = _norm(client.jobs.get(name).status)
        print(f"  pipeline {name}: {status}")
        if status in ("Completed", "Failed", "Canceled", "Cancelled", "Notresponding"):
            break
        time.sleep(poll_s)
    print("  step statuses:")
    for child in client.jobs.list(parent_job_name=name):
        print(f"    {child.display_name or child.name:<42} {_norm(child.status)}")
    return status
